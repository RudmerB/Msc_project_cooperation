/* =======================
This function receives a list of characters and creates a new list in which every 'A'
    is replaced by the sequence 'B' 'L' 'A' 'R' 'A', for a specified number of times.

Input :     symbolSeq   = list of characters containing the intial sequence of symbols (in this case 'A')
            n           = integer that defines the number of steps (Sn)
Output :    symbolSeq   = list of characters containing the new sequence after n number of updates
=======================*/
list<char> ProductionRule(list <char> symbolSeq, int n)                     // Define function
{   
    ofstream instructionsFile ("instructions.csv");                         // (Create and) open output file
    if(!instructionsFile.is_open()){                                        // If opening the output file fails...
        cerr << "Error, cannot open file: instructions.csv" << endl;        // ...print a warning message
        exit(EXIT_FAILURE);                                                 // Exit the program
    }

    list <char> replacement {'B', 'L', 'A', 'R', 'A'};                      // Define a replacement for 'A' 

    for (int x = 0; x <= n; ++x){                                           // Number of updates 
        list <char> newSymbolSeq{};                                         // Create a new, empty list for each loop
        

        // ---------- Writing to output file ----------
        instructionsFile << x << "\t" << symbolSeq.size() << "   \t";       // Write the loop number, sequence length to output file
        for (char i : symbolSeq) {                                          // For each character in symbolSeq...
            instructionsFile << i << " ";                                   // ...write that character to output file
        }
        instructionsFile << endl;                                           // Each iteration is printed on a new line

        if (x == n) break;                                                  // If x == n, do not update the sequence anymore
        
        // ******************  Note on use CHATGPT  ***********************
        // I was struggling to get the current symbolseq to write to the output file.
        // The issue was that the step and sequence length were not on the same line as the 
        // symbolseq they described, this happened because I tried to do both the updating and 
        // the writing to file in the same for loop (char i : symbolSeq) but I could not get that to work.
        // Example of my first output file:
        // 0 1  B L A R A
        // 1 5  B L B L A R A R B L A R A 
        // The 1 and 5 should of course be placed on the line above it...
        // I then asked CHATGPT whether it possible to write it in the same for loop and it suggested
        // it was better to use two for-loops.
        // The line <if (x == n) break;> was generated by CHATGPT;                                      


        // ---------- Updating sequence ----------
        for (char i : symbolSeq){                                           // For each character in Symbolseq

            if (i == 'A') {                                                 // If character is A...
                newSymbolSeq.insert(newSymbolSeq.end(),                     // ...insert at the end of the list newSymbolSeq...
                                    replacement.begin(),                    // ...the characters that are in replacement, which are 
                                    replacement.end());                     // 'B' 'L' 'A' 'R' 'A'
            }
            else {                                                          // If character is not A...
                newSymbolSeq.push_back(i);                                  // Copy the character in symbolSeq at the end of newSymbolSeq
            }
        }
        symbolSeq = newSymbolSeq;                                           // New sequence become reference for following loop
    }
    return symbolSeq;                                                       // Return updated sequence
}


struct structPosition{                      // Define a structure for the current whereabouts of the turtle
    double X = 0.0;                         // Store X-coordinate
    double Y = 0.0;                         // Store Y-coordinate
    double Angle = 0.0;                     // Store direction
    double Scaler = 1.0;                    // Store branch scaler, start at 1
};

struct structHistory{                       // Define a structure for the memory of the turtle
    list <double> lXCoordinates;            // Store past X-coordinates
    list <double> lYCoordinates;            // Store past Y-ccordinates
    list <double> lAngles;                  // Store past directions
    list <double> lScaler;                  // Store past branch scalers
};

class Turtle {                              // Create a Turtle :)
public:
    void ChangeDirection(int i);            // Define a function for the chaning of direction
    void MoveForward();                     // Define a function for the movement of the turtle
    void TurtleRun(list <char> symbolSeq);  // Define a function for the Turtle to execute the command sequence
private:
    structPosition currentPosition;         // Give the turtle concsiousness with above defined structure
    structHistory memory;                   // Give the turtle memory with above defined structure
};


/* =======================
This member function handles the changing of direction, and recalling previous positions and directions.

Input :     int  = the iterator defined in TurtleRun, which is necessary to determine which task the function executes
Output:     none, changes are stored in the class object
=======================*/
void Turtle::ChangeDirection(int i)                                         // Define function
{
    if (i == 'L') {                                                         // If character in symbolSeq is L (will be stated in TurtleRun)
        memory.lXCoordinates.push_back(currentPosition.X);                  // Store current X-coordinate in memory
        memory.lYCoordinates.push_back(currentPosition.Y);                  // Store current Y-coordinate in memory
        memory.lAngles.push_back(currentPosition.Angle);                    // Store current direction in memory
        currentPosition.Angle += 40;                                        // Turn 40 degrees counter-clockwise
        memory.lScaler.push_back(currentPosition.Scaler);                   // Store the current branch scaler in memory
    }
    else if (i == 'R'){                                                     // Else if character in symbolSeq is R (will be stated in TurtleRun)
        currentPosition.X = memory.lXCoordinates.back();                    // Walk back to the last memorized X-coordinate
        currentPosition.Y = memory.lYCoordinates.back();                    // Walk back to the last memorized Y-coordinate
        currentPosition.Angle = memory.lAngles.back() - 40;                 // Restore the last memorized direction and then turn 40 degrees clockwise
        currentPosition.Scaler = memory.lScaler.back();                     // Restore the last memozized branch scaler 

        memory.lXCoordinates.pop_back();                                    // Remove the last memorized location, direction, and scaler
        memory.lYCoordinates.pop_back();                                    // (Which will be the values the turtle currently has)
        memory.lAngles.pop_back();
        memory.lScaler.pop_back();
    }
}
// Access last element of list with .back() :
// https://www.geeksforgeeks.org/cpp/how-to-access-the-last-element-of-a-list-in-cpp/
// Remove last element with pop :

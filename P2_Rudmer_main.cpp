/* =======================
This member function handles the movement of the turtle and scales the branches that are produced by turtle

Input :     none, variables are taken from the class object
Output:     none, changes are stored in the class object
=======================*/
void Turtle::MoveForward()                                                  // Define function
{
    currentPosition.Scaler *= 0.8;                                          // When moving forward, scale the upcomming branch down with ratio 5/4
    currentPosition.X += currentPosition.Scaler *                           // New X-coordinate will be current position + the scaled length *
                         cos(2 * M_PI * currentPosition.Angle / 360);       // the direction of the turtle
    currentPosition.Y += currentPosition.Scaler *                           // New Y-coordinate will be current position + the scaled length *
                         sin(2 * M_PI * currentPosition.Angle / 360);       // the direction of the turtle
}


/* =======================
This member function handles the commands the turtle receives from symbolSeq

Input :     symbolSeq   = list of characters containing the new sequence after n number of updates
Output:     none, coordinates of turtle are written to output file
=======================*/
void Turtle::TurtleRun(list <char> symbolSeq)                               // Define function
{
    ofstream coordinatesFile ("coordinates.csv");                           // (Create and) open output file
    if(!coordinatesFile.is_open()){                                         // If opening the output file fails...
        cerr << "Error, cannot open file: coordinates.csv" << endl;         // ...print a warning message
        exit(EXIT_FAILURE);                                                 // Exit the program
    }

    for (char i : symbolSeq) {                                              // For each character in symbolSeq (updated)
        if (i == 'A' || i == 'B') {                                         // If chararacter is A or B...
            coordinatesFile << currentPosition.X << ","                     // ...write current X- and
                            << currentPosition.Y << "\n";                   // Y-coordinate to output file (from class object)
            MoveForward();                                                  // Call MoveForward function
            coordinatesFile << currentPosition.X << ","                     // Write current X- and 
                            << currentPosition.Y << "\n\n";                 // Y-coordinate to output file (after movement)
        }
        else {                                                              // If character is not A or B
            ChangeDirection(i);                                             // Call ChangeDirection function
        }
    }
}



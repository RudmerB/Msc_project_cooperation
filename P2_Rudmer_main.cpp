int main()                                              // Define main
{   
    list<char> symbolSeq{'A'};                          // Create the initial symbolSeq
    const int n = 15;                                    // Define the number of iterations
    
    cout << "Creating command sequence for turtle...";  // Progress message
    symbolSeq = ProductionRule(symbolSeq, n);           // Create the command sequence for turtle 
    
    cout << "\n\nTurtle is drawing...";                 // Progress message
    Turtle BestTurtle;                                  // Give life to turtle
    BestTurtle.TurtleRun(symbolSeq);                    // Let the turtle run according to the command sequence

    cout << "\n\nTurtle has made something for you!\n"  // Completed execution message
         << "Check coordinates.csv & instructions.csv";
    return 0;                                           // Return
}